const fs = require('node:fs/promises');
const path = require('node:path');

// Browsers launch native messaging hosts directly, so Linux needs a small
// executable shell wrapper. Windows uses a .cmd for development runs and a
// compiled launcher (see prepareNativeHost) for installed copies.
async function writeNativeHostLauncher(directory, executable, platform = process.platform) {
  const hostScript = path.join(directory, 'native-host.cjs');
  if (platform === 'win32') {
    const quoteBatch = value => String(value).replaceAll('%', '%%');
    await fs.writeFile(path.join(directory, 'native-host.cmd'),
      `@echo off\r\nset ELECTRON_RUN_AS_NODE=1\r\n"${quoteBatch(executable)}" "%~dp0native-host.cjs"\r\n`);
    return path.join(directory, 'native-host.cmd');
  }
  // Single-quote for POSIX sh. The runtime path is embedded because browsers
  // start the host without inheriting the desktop app's environment.
  const quoteShell = value => `'${String(value).replaceAll("'", `'\\''`)}'`;
  const script = [
    '#!/bin/sh',
    '# Generated by Awesome Downloader. Safe to delete when the app is removed.',
    'export ELECTRON_RUN_AS_NODE=1',
    `exec ${quoteShell(executable)} ${quoteShell(hostScript)} "$@"`,
    ''
  ].join('\n');
  const launcher = path.join(directory, 'native-host.sh');
  await fs.writeFile(launcher, script, { mode: 0o755 });
  // writeFile only applies the mode when creating the file; enforce it when
  // the launcher is refreshed after an update or a permission change.
  await fs.chmod(launcher, 0o755);
  return launcher;
}

module.exports = { writeNativeHostLauncher };
